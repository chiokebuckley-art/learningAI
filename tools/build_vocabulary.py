"""Build js/vocabulary-data.js from data/ai-curriculum-seed.json.

The seed glossary lists terms by category but does not say which lesson
module explains each term, so TERM_MODULES below is the editorial mapping.
Run from the repo root after editing either file:

    python3 tools/build_vocabulary.py
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
SEED = ROOT / "data" / "ai-curriculum-seed.json"
OUT = ROOT / "js" / "vocabulary-data.js"


def ids(*ranges):
    out = []
    for r in ranges:
        if isinstance(r, tuple):
            out += [f"T{n:03d}" for n in range(r[0], r[1] + 1)]
        else:
            out.append(f"T{r:03d}")
    return out


MODULE_TERMS = {
    "L01": ids((1, 2), (4, 10), 194, 195),
    "L02": ids((13, 19), (26, 30)),
    "L03": ids(11, 12, (22, 25), (31, 38)),
    "L04": ids(3, (50, 53)),
    "L05": ids((61, 66), 105),
    "L06": ids((67, 72), 193),
    "L07": ids(20, 21, (39, 49), (56, 58)),
    "L08": ids(54, 55, 59, 60, (73, 77), (87, 89), 92),
    "L09": ids((78, 86), 109, 111),
    "L10": ids(90, 91, (93, 104), (106, 108), 110, 112),
    "L11": ids((118, 129)),
    "L12": ids((113, 117), (138, 144)),
    "L13": ids((130, 137)),
    "L14": ids((175, 192), 197),
    "L15": ids((145, 154), (161, 165)),
    "L16": ids((155, 160), (166, 174), 196),
}

MODULE_FIELDS = ("id", "title", "question", "explanation", "mechanics", "misconception", "quiz", "answer")


def main():
    seed = json.loads(SEED.read_text(encoding="utf-8"))
    term_ids = [g["id"] for g in seed["glossary"]]

    term_module = {}
    for mod, terms in MODULE_TERMS.items():
        for t in terms:
            if t in term_module:
                raise SystemExit(f"{t} is mapped to both {term_module[t]} and {mod}")
            term_module[t] = mod
    missing = [t for t in term_ids if t not in term_module]
    unknown = [t for t in term_module if t not in term_ids]
    if missing or unknown:
        raise SystemExit(f"unmapped terms: {missing}; unknown terms: {unknown}")

    categories = []
    for g in seed["glossary"]:
        if g["category"] not in categories:
            categories.append(g["category"])

    terms = [
        {
            "id": g["id"],
            "category": g["category"],
            "term": g["term"],
            "definition": g["definition"],
            "module": term_module[g["id"]],
            "sources": [f"web:{s}" for s in g["sources"]],
        }
        for g in seed["glossary"]
    ]
    modules = []
    for m in seed["modules"]:
        entry = {k: m[k] for k in MODULE_FIELDS}
        raw = m["sources"]
        # The seed stores some module source lists as a JSON string, others as a list.
        nums = json.loads(raw) if isinstance(raw, str) else raw
        entry["sources"] = [f"web:{s}" for s in nums]
        modules.append(entry)
    sources = {s["id"]: {"title": s["title"], "url": s["url"]} for s in seed["sources"]}

    data = {
        "version": seed["version"],
        "reviewDate": seed["review_date"],
        "scope": seed["scope"],
        "categories": categories,
        "terms": terms,
        "modules": modules,
        "sources": sources,
    }
    OUT.write_text(
        "/**\n"
        " * AI Words vocabulary data. GENERATED by tools/build_vocabulary.py from\n"
        " * data/ai-curriculum-seed.json; edit those, then re-run the script.\n"
        " */\n\n"
        "const VOCABULARY_DATA = " + json.dumps(data, indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8",
    )
    print(f"wrote {OUT.relative_to(ROOT)}: {len(terms)} terms, {len(modules)} modules, {len(sources)} sources")


if __name__ == "__main__":
    main()
